-- ==================== ระบบบันทึกเพลง (Saved Songs System) ====================
local SavedSongs = {}
local SAVE_FILE_NAME = "Honkuki_SavedSongs.json"

local function loadSavedSongs()
    if readfile and isfile and isfile(SAVE_FILE_NAME) then
        local success, data = pcall(function()
            return HttpService:JSONDecode(readfile(SAVE_FILE_NAME))
        end)
        if success and type(data) == "table" then
            SavedSongs = data
            return
        end
    end
    SavedSongs = {}
end

local function saveSavedSongs()
    if writefile then
        pcall(function()
            writefile(SAVE_FILE_NAME, HttpService:JSONEncode(SavedSongs))
        end)
    end
end

local function addSavedSong(songId)
    if not songId or songId == "" then return false end
    songId = tostring(songId)
    for _, id in ipairs(SavedSongs) do
        if id == songId then return false end
    end
    table.insert(SavedSongs, songId)
    saveSavedSongs()
    return true
end

local function removeSavedSong(songId)
    songId = tostring(songId)
    for i, id in ipairs(SavedSongs) do
        if id == songId then
            table.remove(SavedSongs, i)
            saveSavedSongs()
            return true
        end
    end
    return false
end

